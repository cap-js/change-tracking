/**
 * Generates simplified H2 Java trigger classes for .drafts shadow tables.
 *
 * These triggers record which entity types within a draft were touched, writing
 * into sap_changelog_DraftChanges without any column-level comparison.  False
 * positives (a field changed and changed back) are intentionally accepted — the
 * CAP Java delta-save path runs a CdsDiffProcessor confirmation pass anyway.
 *
 * Class names use the _dct suffix to avoid collision with active-side _ct classes.
 */
const utils = require('../utils/change-tracking.js');
const { TRIGGER_JAVA_PACKAGE } = require('./java-codegen.js');

const DRAFT_CHANGES_TABLE = 'SAP_CHANGELOG_DRAFTCHANGES';

/**
 * Maps a .drafts entity name to a Java class name.
 * e.g. 'AdminService.BookStores.drafts' → 'AdminService_BookStores_drafts_dct'
 */
function _draftTriggerClassName(draftsEntityName) {
  return `${draftsEntityName.replace(/\./g, '_').replace(/[^a-zA-Z0-9_]/g, '_')}_dct`;
}

/**
 * Returns the H2 column name for DraftAdministrativeData_DraftUUID as stored
 * in the .drafts table. H2 uppercases unquoted identifiers and the CDS compiler
 * flattens the association path with underscores.
 */
function _draftUUIDColumn() {
  return 'DRAFTADMINISTRATIVEDATA_DRAFTUUID';
}

/**
 * Generates the Java source for a draft-delta trigger class.
 *
 * @param {string} draftsEntityName  - model name of the .drafts entity (e.g. 'AdminService.BookStores.drafts')
 * @param {string} activeEntityName  - underlying DB entity name recorded in DraftChanges.entityName
 * @param {boolean} isRoot           - when true, suppress the INSERT body (draft-open copy is not a user change)
 */
function _generateDraftTriggerClass(draftsEntityName, activeEntityName, isRoot) {
  const className = _draftTriggerClassName(draftsEntityName);
  const draftUUIDCol = _draftUUIDColumn();

  const mergeSQL = (ct, rowRef) =>
    `"MERGE INTO ${DRAFT_CHANGES_TABLE}(DRAFTUUID, ENTITYNAME, CHANGETYPE) " +\n` +
    `                    "KEY(DRAFTUUID, ENTITYNAME, CHANGETYPE) VALUES(?, '${activeEntityName}', '${ct}')"`;

  const updateBlock = `if (isUpdate) {
            try (java.sql.PreparedStatement stmt = conn.prepareStatement(
                    ${mergeSQL('update', 'newRow')})) {
                stmt.setString(1, newRow.getString("${draftUUIDCol}"));
                stmt.executeUpdate();
            }
        }`;

  const childBlocks = isRoot ? '' : `
        if (isInsert) {
            try (java.sql.PreparedStatement stmt = conn.prepareStatement(
                    ${mergeSQL('insert', 'newRow')})) {
                stmt.setString(1, newRow.getString("${draftUUIDCol}"));
                stmt.executeUpdate();
            }
        } else if (isUpdate) {
            try (java.sql.PreparedStatement stmt = conn.prepareStatement(
                    ${mergeSQL('update', 'newRow')})) {
                stmt.setString(1, newRow.getString("${draftUUIDCol}"));
                stmt.executeUpdate();
            }
        } else if (isDelete) {
            try (java.sql.PreparedStatement stmt = conn.prepareStatement(
                    ${mergeSQL('delete', 'oldRow')})) {
                stmt.setString(1, oldRow.getString("${draftUUIDCol}"));
                stmt.executeUpdate();
            }
        }`;

  const body = isRoot ? `        ${updateBlock}` : `        ${childBlocks.trim()}`;

  const source = `package ${TRIGGER_JAVA_PACKAGE};

import org.h2.tools.TriggerAdapter;
import java.sql.Connection;
import java.sql.ResultSet;
import java.sql.SQLException;

/**
 * Draft-delta trigger for entity {@code ${activeEntityName}} (.drafts shadow table).
 * Records that the draft was touched; no column-level comparison is performed.
 * Generated by @cap-js/change-tracking. Do not edit.
 */
public class ${className} extends TriggerAdapter {

    @Override
    public void fire(Connection conn, ResultSet oldRow, ResultSet newRow) throws SQLException {
        boolean isInsert = oldRow == null;
        boolean isDelete = newRow == null;
        boolean isUpdate = !isInsert && !isDelete;
${body}
    }
}
`;

  return { className, source };
}

/**
 * Entry point called from h2/register.js for each draft entity descriptor.
 *
 * @param {object} descriptor - { draftsEntityName, activeEntityName, isRoot }
 * @returns {{ ddl: string, java: { className: string, source: string } }}
 */
function generateH2DraftTrigger({ draftsEntityName, activeEntityName, isRoot }) {
  const tableName = utils.transformName(draftsEntityName);
  const { className, source } = _generateDraftTriggerClass(draftsEntityName, activeEntityName, isRoot);
  const fqcn = `${TRIGGER_JAVA_PACKAGE}.${className}`;
  const ddl = `CREATE TRIGGER ${tableName}_dct AFTER INSERT, UPDATE, DELETE ON ${tableName} FOR EACH ROW CALL '${fqcn}';`;
  return { ddl, java: { className, source } };
}

module.exports = { generateH2DraftTrigger };
